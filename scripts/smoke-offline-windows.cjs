'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),os=require('node:os'),path=require('node:path');
const {execFileSync}=require('node:child_process');
const {_electron}=require('playwright-core');
const {componentsReady}=require('../src/desktop/browser-components.cjs');
assert.equal(process.platform,'win32','Run this check on Windows');
const root=path.resolve(__dirname,'..'),version=require('../package.json').version.replace(/\.0$/,'');
const output=path.join(root,'build/test-results');fs.mkdirSync(output,{recursive:true});
const temporary=fs.mkdtempSync(path.join(os.tmpdir(),'paperdesk-offline-'));
const install=path.join(temporary,'Paperdesk'),data=path.join(temporary,'data');
const runtime=path.join(install,'resources/runtime');
const installer=path.join(root,'build/work/windows-x64-offline',`Paperdesk-${version}-Windows-Offline.exe`);
const env={...process.env,HTTP_PROXY:'http://127.0.0.1:9',HTTPS_PROXY:'http://127.0.0.1:9',ALL_PROXY:'http://127.0.0.1:9',NO_PROXY:'localhost,127.0.0.1',PAPERDESK_TEST_DATA_DIR:data,PAPERDESK_TEST_OFFLINE:'1'};
delete env.PAPERDESK_TEST_COMPONENTS_DIR;
delete env.PLAYWRIGHT_BROWSERS_PATH;
const report={version,checks:[],errors:[]};
let app;
const launch=()=>_electron.launch({executablePath:path.join(install,'Paperdesk.exe'),args:[],env,timeout:60000});
(async()=>{
 const started=Date.now();
 execFileSync(installer,['/S',`/D=${install}`],{env,timeout:300000,stdio:'inherit'});
 assert.ok(fs.existsSync(path.join(install,'Paperdesk.exe')));
 assert.ok(componentsReady(path.join(runtime,'browser-module/playwright-core'),path.join(runtime,'browsers'),'win32'));
 report.installSeconds=Math.round((Date.now()-started)/1000);
 report.checks.push('Silent NSIS installation completes with an unreachable download proxy and all five bundled components');
 execFileSync(path.join(runtime,'node/node.exe'),[path.join(root,'scripts/smoke-browsers.cjs')],{env:{...env,PAPERDESK_TEST_RUNTIME:runtime},timeout:90000,stdio:'inherit'});
 report.checks.push('Installed Chromium and Firefox launch and render local content');
 app=await launch();let page=await app.firstWindow();
 page.on('pageerror',error=>report.errors.push(error.message));
 await page.getByRole('heading',{name:'欢迎使用 Paperdesk'}).waitFor({timeout:30000});
 assert.ok(page.url().startsWith('paperdesk://app/'));
 assert.equal((await page.evaluate(()=>window.paperdesk.info())).version,version);
 await page.screenshot({path:path.join(output,'offline-windows-welcome.png')});
 await page.getByRole('textbox',{name:'我的姓名'}).fill('示例作者');
 await page.getByRole('textbox',{name:'其他署名'}).fill('Example Author');
 await page.getByRole('button',{name:'保存并开始'}).click();
 await page.getByRole('heading',{name:'添加期刊账号',exact:true}).waitFor();
 await page.getByRole('button',{name:'取消',exact:true}).click();
 await page.getByRole('button',{name:/投稿总览/}).click();
 assert.equal(fs.existsSync(path.join(data,'components')),false,'First launch must use bundled components without creating a download cache');
 report.checks.push('Fresh profile reaches the main UI and saves onboarding without downloading components');
 await page.screenshot({path:path.join(output,'offline-windows-overview.png')});
 await app.close();app=null;
 app=await launch();page=await app.firstWindow();
 await page.getByRole('button',{name:/投稿总览/}).waitFor({timeout:30000});
 assert.equal(await page.getByRole('heading',{name:'欢迎使用 Paperdesk'}).count(),0);
 assert.equal(fs.existsSync(path.join(data,'components')),false);
 report.checks.push('Relaunch preserves the profile and reuses bundled components');
 assert.deepEqual(report.errors,[]);
 await app.close();app=null;
 report.ok=true;
})().catch(error=>{report.ok=false;report.error=error.stack;console.error(error);process.exitCode=1;}).finally(async()=>{
 if(app)await app.close().catch(()=>{});
 fs.writeFileSync(path.join(output,'offline-installer-windows.json'),JSON.stringify(report,null,2));
 console.log(JSON.stringify(report,null,2));
});
